// Bundles the support desk's working time and SLA rules into the email-in
// Edge Function so tickets opened by email get the same due time as tickets
// opened in the app: app/src/lib/sla.ts is the one source of truth.
//
//   npm run build:support-fn              # regenerate
//   npm run build:support-fn -- --check   # CI: fail if the bundle is stale
import { build } from 'esbuild'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const entry = resolve(here, '../src/lib/sla.ts')
const out = resolve(here, '../../supabase/functions/support-email-in/sla.bundle.js')

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  write: false,
  legalComments: 'none',
  banner: {
    js: '// GENERATED by app/scripts/build-support-function.mjs from app/src/lib/sla.ts. Do not edit.',
  },
})
const code = result.outputFiles[0].text

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current !== code) {
    console.error('sla.bundle.js is out of date. Run: npm run build:support-fn (in app/) and commit.')
    process.exit(1)
  }
  console.log('sla.bundle.js is up to date')
} else {
  writeFileSync(out, code)
  console.log(`wrote ${out}`)
}
