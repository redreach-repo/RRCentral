// Bundles shared app rules into the Edge Functions that need them, so the
// app and the function can never disagree:
// * support-email-in gets the working time and SLA rules (src/lib/sla.ts),
//   so tickets opened by email get the same due time as tickets opened in the app.
// * worshiphub-read gets the WorshipHub field filter (src/lib/worshiphub.ts),
//   so only the agreed account level fields ever leave the function.
//
//   npm run build:support-fn              # regenerate
//   npm run build:support-fn -- --check   # CI: fail if a bundle is stale
import { build } from 'esbuild'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const bundles = [
  { entry: 'src/lib/sla.ts', out: '../supabase/functions/support-email-in/sla.bundle.js' },
  { entry: 'src/lib/worshiphub.ts', out: '../supabase/functions/worshiphub-read/worshiphub.bundle.js' },
]

let stale = false
for (const b of bundles) {
  const entry = resolve(here, '..', b.entry)
  const out = resolve(here, '..', b.out)
  const name = b.out.split('/').pop()
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    legalComments: 'none',
    banner: {
      js: `// GENERATED by app/scripts/build-support-function.mjs from app/${b.entry}. Do not edit.`,
    },
  })
  const code = result.outputFiles[0].text

  if (process.argv.includes('--check')) {
    const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
    if (current !== code) {
      console.error(`${name} is out of date. Run: npm run build:support-fn (in app/) and commit.`)
      stale = true
    } else {
      console.log(`${name} is up to date`)
    }
  } else {
    writeFileSync(out, code)
    console.log(`wrote ${out}`)
  }
}
if (stale) process.exit(1)
