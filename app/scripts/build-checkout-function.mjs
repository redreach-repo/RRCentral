// Bundles the shop's server-side checkout rules (catalog prices, validation)
// into the Supabase Edge Function so the live site and local dev share one
// source of truth: app/src/shop/checkout.ts.
//
//   npm run build:checkout-fn          # regenerate
//   npm run build:checkout-fn -- --check   # CI: fail if the bundle is stale
import { build } from 'esbuild'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const entry = resolve(here, '../src/shop/checkout.ts')
const out = resolve(here, '../../supabase/functions/create-checkout-session/checkout.bundle.js')

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  write: false,
  legalComments: 'none',
  banner: {
    js: '// GENERATED by app/scripts/build-checkout-function.mjs from app/src/shop/checkout.ts — do not edit.',
  },
})
const code = result.outputFiles[0].text

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current !== code) {
    console.error('checkout.bundle.js is out of date. Run: npm run build:checkout-fn (in app/) and commit.')
    process.exit(1)
  }
  console.log('checkout.bundle.js is up to date')
} else {
  writeFileSync(out, code)
  console.log(`wrote ${out}`)
}
