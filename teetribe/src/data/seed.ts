function mockupUrl(colorHex: string, view: 'front' | 'back', label: string) {
  const color = colorHex.replace('#', '')
  return `/api/mockup?color=${color}&view=${view}&label=${encodeURIComponent(label)}`
}

function makeVariants(
  productId: string,
  sizes: readonly string[],
  colors: typeof COLORS,
  baseStock = 12,
): ProductVariant[] {
  const variants: ProductVariant[] = []
  for (const size of sizes) {
    for (const { color, colorHex } of colors) {
      variants.push({
        id: `${productId}-${size}-${color.toLowerCase()}`,
        sku: `TT-${productId}-${size}-${color.slice(0, 3).toUpperCase()}`,
        size: size as ProductVariant['size'],
        color,
        colorHex,
        stock: baseStock + Math.floor(Math.random() * 8),
      })
    }
  }
  return variants
}

function makeImages(label: string, colorHex: string) {
  return [
    { id: '1', url: mockupUrl(colorHex, 'front', label), alt: `${label} front`, view: 'front' as const, sort: 1 },
    { id: '2', url: mockupUrl(colorHex, 'back', label), alt: `${label} back`, view: 'back' as const, sort: 2 },
  ]
}

