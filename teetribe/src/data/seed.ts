export function getProduct(slugOrId: string): Product | undefined {
  return products.find((p) => p.slug === slugOrId || p.id === slugOrId)
}

export function getCollection(slug: CollectionSlug): Collection | undefined {
  return collections.find((c) => c.slug === slug)
}

export function getBestSellers(limit = 8): Product[] {
  return products.filter((p) => p.bestSeller && p.isActive).slice(0, limit)
}

export function getActiveDrop(): Product | undefined {
  const now = Date.now()
  return products.find(
    (p) => p.isDrop && p.isActive && p.dropClosesAt && new Date(p.dropClosesAt).getTime() > now,
  )
}

export function relatedProducts(product: Product, limit = 4): Product[] {
  return products
    .filter((p) => p.id !== product.id && p.isActive && (p.collection === product.collection || p.type === product.type))
    .slice(0, limit)
}

export function totalStock(product: Product): number {
  return product.variants.reduce((sum, v) => sum + v.stock, 0)
}

export function getAllProducts(): Product[] {
  return products.filter((p) => p.isActive)
}

export function getProductsByCollection(slug: CollectionSlug): Product[] {
  return products.filter((p) => p.collection === slug && p.isActive)
}
